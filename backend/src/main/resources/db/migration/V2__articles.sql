CREATE TABLE games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    steam_app_id BIGINT NOT NULL UNIQUE
);

CREATE TABLE sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL
);

CREATE TABLE articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL REFERENCES sources(id),
    game_id BIGINT REFERENCES games(id),
    external_id VARCHAR(128) NOT NULL,
    title VARCHAR(300) NOT NULL,
    body TEXT NOT NULL,
    original_url VARCHAR(2048) NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(12) NOT NULL CHECK (status IN ('PUBLISHED', 'HIDDEN')),
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_articles_source_external UNIQUE (source_id, external_id)
);

CREATE INDEX ix_articles_publication ON articles (status, published_at DESC, id DESC);
CREATE INDEX ix_articles_game_publication ON articles (game_id, status, published_at DESC, id DESC);
